C=======================================================================
C MODIFIED WILSON-DOVEY OUT-OF-CORE ACTIVE-COLUMN SOLVER, WITH THE
C TWO CHANGES DESCRIBED BY HOIT (1986), "EQUATION SOLVER
C MODIFICATIONS" (PAGE 249):
C
C 1. "THE ORIGINAL BLOCK READ SUBROUTINE [TAPES] WAS REPLACED WITH
C    A DIRECT ACCESS VERSION."  -> DABLK BELOW. STIFFNESS BLOCKS ARE
C    RECORDS 1..NBLK, LOAD BLOCKS ARE RECORDS NBLK+1..NBLK+NBLL OF
C    ONE DIRECT ACCESS FILE (AS WRITTEN BY ASEMBL/ASEMLD/MLOAD),
C    AND REDUCED BLOCKS OVERWRITE THEIR OWN RECORDS.
C 2. "THE LOAD VECTOR WAS SWITCHED FROM THE FIRST BLOCK TO THE
C    SECOND ... ALLOWS FOR THE COEFFICIENT MATRIX TO REMAIN IN
C    MEMORY AND THE RHS TO BE BLOCKED AND SWAPPED."  -> IN THE LOAD
C    PHASE THE RHS IS IN B AND THE COEFFICIENT BLOCK IN A. A
C    COEFFICIENT BLOCK IS ONLY READ IF IT IS NOT ALREADY RESIDENT
C    IN A, SO A SINGLE-BLOCK (IN-CORE) MATRIX IS NEVER RE-READ.
C
C HOIT DID NOT PUBLISH THE MODIFIED SOLVER. THIS IS A
C RECONSTRUCTION FROM HIS DESCRIPTION, BUILT ON THE PUBLISHED
C WILSON & DOVEY (1978) APPENDIX C ROUTINES SORE AND BLKOP. BLKOP
C IS UNCHANGED APART FROM REAL*8 (SIMPAL IS DOUBLE PRECISION).
C
C ARGUMENTS OF SORED (AS SORE, EXCEPT WHERE NOTED)
C   A(MAXA)  COEFFICIENT WORK BLOCK          (WAS A(MAXT))
C   B(MAXB)  SECOND BLOCK: PREVIOUS COEFFICIENT BLOCK DURING
C            FACTORIZATION, LOAD BLOCK DURING REDUCTION. IF NBLK>1
C            MAXB MUST BE >= MAXA. IF NBLK=1, B ONLY NEEDS TO HOLD
C            A LOAD BLOCK (>= NEQ).
C   D(NEQ)   DIAGONAL TERMS OF REDUCED MATRIX (KEEP BETWEEN CALLS)
C   MA,MB    DIAGONAL POINTERS FOR A AND B (MAXC EACH)
C   NT       DIRECT ACCESS UNIT (REPLACES THE 4 TAPE NUMBERS)
C   KKK      1..5 AS IN SORE
C
C REFERENCE
C
C Hoit, M. (1986). An Updated Out-of-Core Equation Solver.
C Computer-Aided Civil and Infrastructure Engineering,
C Volume 1, Issue 3, Pages 247-254.
C https://doi.org/10.1111/j.1467-8667.1986.tb00132.x.
C
C=======================================================================
C
      SUBROUTINE SORED (A,B,D,MA,MB,NEQ,LEQ,NBLK,NBLL,MAXA,MAXB,MAXC,
     *                  NT,KKK)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION A(MAXA),B(MAXB),D(NEQ),MA(MAXC),MB(MAXC)
      DIMENSION KA(4),KB(4)
      COMMON /DASTAT/ NDAR,NDAW,NCRLD
C     IRES = NUMBER OF THE COEFFICIENT BLOCK NOW HELD IN A (0 = NONE)
      IRES=0
      GOTO (100,100,100,300,300) KKK
C-----BLOCK-BY-BLOCK TRIANGULARIZATION OF MATRIX
  100 IF (NBLK.GT.1.AND.MAXB.LT.MAXA) THEN
        WRITE(*,*) ' SORED: MAXB MUST BE >= MAXA WHEN NBLK > 1'
        STOP 1
      ENDIF
      DO 200 N=1,NBLK
C     1. MOVE PREVIOUSLY REDUCED BLOCK TO B
      IF (N.EQ.1) GOTO 110
      CALL BLKOP (A,B,D,MA,MB,KA,KB,NEQ,LEQ,MAXA,MAXC,1)
C     2. READ NEW BLOCK N
  110 CALL DABLK (NT,N,A,NW,MAXA,MA,MAXC,KA,1)
C     3. OPERATE ON BLOCK N WITH BLOCK M
      M = KA(2)
      IF (M.EQ.N) GOTO 160
      NM=N-1
      IF (M.EQ.NM) GOTO 140
C     READ BLOCK M (ALREADY REDUCED)
  120 CALL DABLK (NT,M,B,NW,MAXB,MB,MAXC,KB,1)
  140 CALL BLKOP (A,B,D,MA,MB,KA,KB,NEQ,LEQ,MAXA,MAXC,2)
      M = M+1
      IF (M.LT.N) GOTO 120
C     4. SELF-REDUCTION OF BLOCK N
  160 CALL BLKOP (A,A,D,MA,MA,KA,KA,NEQ,LEQ,MAXA,MAXC,3)
C     5. WRITE REDUCED BLOCK N OVER ITS OWN RECORD
      NW=MA(KA(4)-KA(3)+1)
      CALL DABLK (NT,N,A,NW,MAXA,MA,MAXC,KA,2)
  200 CONTINUE
      IRES=NBLK
      IF (KKK.EQ.3) RETURN
C-----REDUCTION OF LOAD BLOCKS (LOAD IN B, COEFFICIENTS IN A)
  300 DO 400 M=1,NBLL
      NR=NBLK+M
C     1. READ LOAD BLOCK M
      CALL DABLK (NT,NR,B,NW,MAXB,MB,MAXC,KB,1)
C     2. FORWARD REDUCTION OF LOAD BLOCK M
      IF (KKK.EQ.5) GOTO 335
      DO 320 N=1,NBLK
      IF (IRES.NE.N) THEN
        CALL DABLK (NT,N,A,NW,MAXA,MA,MAXC,KA,1)
        NCRLD=NCRLD+1
        IRES=N
      ENDIF
      CALL BLKOP (B,A,D,MB,MA,KB,KA,NEQ,LEQ,MAXB,MAXC,4)
  320 CONTINUE
C     3. BACKWARD REDUCTION OF LOAD BLOCK M
  330 IF (KKK.EQ.4) GOTO 390
      IF (KKK.EQ.2) GOTO 390
  335 N=NBLK
  340 IF (IRES.NE.N) THEN
        CALL DABLK (NT,N,A,NW,MAXA,MA,MAXC,KA,1)
        NCRLD=NCRLD+1
        IRES=N
      ENDIF
      CALL BLKOP (B,A,D,MB,MA,KB,KA,NEQ,LEQ,MAXB,MAXC,5)
      N=N-1
      IF (N.GT.0) GOTO 340
C     4. WRITE RESULTS OVER THE LOAD RECORD
  390 NW=(KB(4)-KB(3)+1)*NEQ
      CALL DABLK (NT,NR,B,NW,MAXB,MB,MAXC,KB,2)
  400 CONTINUE
      RETURN
      END
C
C=======================================================================
      SUBROUTINE DABLK (NT,NR,X,NW,MAXX,MC,MAXC,KF,KK)
C-----DIRECT ACCESS REPLACEMENT FOR TAPES. RECORD NR OF UNIT NT HOLDS
C     KF(4), MC(MAXC), NW, X(NW)   (INTEGERS FIRST, SO THE REAL PART CAN
C     BE ANY LENGTH UP TO THE RECORD SIZE)
C     KK=1 READ   KK=2 WRITE
C     KK=3 WRITE WITH MC WRITTEN AS ZEROS (LOAD BLOCKS FROM ASSEMBLY)
C     KK=4 READ WITHOUT STORING MC
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION X(MAXX),MC(MAXC),KF(4)
      COMMON /DASTAT/ NDAR,NDAW,NCRLD
      IF (KK.EQ.1) THEN
        READ (NT,REC=NR) KF,(MC(I),I=1,MAXC),NW,
     *       (X(I),I=1,MIN(NW,MAXX))
        NDAR=NDAR+1
      ELSE IF (KK.EQ.4) THEN
        READ (NT,REC=NR) KF,(IDUM,I=1,MAXC),NW,
     *       (X(I),I=1,MIN(NW,MAXX))
        NDAR=NDAR+1
      ELSE
        IF (NW.GT.MAXX) GOTO 900
        IF (KK.EQ.2) THEN
          WRITE (NT,REC=NR) KF,(MC(I),I=1,MAXC),NW,(X(I),I=1,NW)
        ELSE
          IZ=0
          WRITE (NT,REC=NR) KF,(IZ,I=1,MAXC),NW,(X(I),I=1,NW)
        ENDIF
        NDAW=NDAW+1
      ENDIF
      IF (NW.GT.MAXX) GOTO 900
      RETURN
  900 WRITE(*,*) ' DABLK: BLOCK',NR,' HAS',NW,' WORDS, ARRAY HAS',MAXX
      STOP 1
      END
C=======================================================================
C     BLKOP - WILSON & DOVEY (1978) APPENDIX C, UNCHANGED EXCEPT REAL*8
C     AND (*) DUMMY DIMENSIONS (PRINTED AS (1)).
C=======================================================================
      SUBROUTINE BLKOP (A,B,D,MA,MB,KA,KB,NEQ,LEQ,MAXT,MAXC,KK)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION A(*),B(*),MA(*),MB(*),KA(4),KB(4),D(*)
      GOTO (100,300,300,300,500),KK
C
C     1. MOVE A ARRAY TO B
C
  100 DO 110 I=1,4
  110 KB(I)=KA(I)
      DO 120 I=1,MAXC
  120 MB(I)=MA(I)
      DO 130 I=1,MAXT
  130 B(I)=A(I)
      RETURN
C
C     2. REDUCE BLOCK A BY BLOCK B
C
  300 NTA=KA(4)-KA(3)+1
      NTB=KB(4)-KB(3)+1
      KJ=0
      DO 390 J=1,NTA
      IF (KK.EQ.4) MA(J)=J*NEQ
      JJ=KA(3)+J-1
      IF (KK.EQ.4) JJ=NEQ
      KHJ=MA(J)-KJ
      IL=NTB
      IF (KK.EQ.3) IL=J
      KI=0
      DO 380 I=1,IL
      II=KB(3)+I-1
      KHI=MB(I)-KI
      KH=MIN0(KHI,KHJ-JJ+II)
      KF=MB(I)-KH+1
      KL=MB(I)-MAX0(1,II-LEQ)
      SS=0.0
      IJ=MA(J)-JJ+II
      IF (KK.NE.3) GOTO 310
      IF (I.EQ.J) GOTO 355
  310 IF (KF.GT.KL) GOTO 380
      IC=IJ-MB(I)
      DO 320 K=KF,KL
  320 SS=SS+B(K)*A(K+IC)
      A(IJ)=A(IJ)-SS
      GOTO 380
  355 KD=JJ-KHJ+1-KF
      IF (KF.GT.KL) GOTO 380
C     REDUCE COLUMN BY ITSELF
      DO 370 K=KF,KL
      AD=D(KD+K)
      IF (AD) 360,370,360
  360 T=A(K)/AD
      SS=SS+T*A(K)
      A(K)=T
  370 CONTINUE
      A(IJ)=A(IJ)-SS
      IF (KK.EQ.4) D(II)=B(KI)
  380 KI=MB(I)
      KJ=MA(J)
      IF (KK.EQ.4) GOTO 390
      D(JJ)=A(KJ)
  390 CONTINUE
      IF (KK.EQ.4.AND.KB(4).EQ.NEQ) GOTO 400
      RETURN
C     DIVIDE LOADS BY DIAGONALS
  400 KJ=0
      DO 450 J=1,NTA
      MA(J)=J*NEQ
      KHJ=MA(J)-KJ
      IF=NEQ-KHJ+1
      IF (IF.GT.LEQ) GOTO 450
      DO 440 II=IF,LEQ
      IF (D(II)) 430,440,430
  430 A(II+KJ)=A(II+KJ)/D(II)
  440 CONTINUE
  450 KJ=MA(J)
      RETURN
C
C     3. BACK-SUBSTITUTION
C
  500 II=KB(4)
      NTA=KA(4)-KA(3)+1
  520 I=II-KB(3)+1
      IF (I.LE.0) RETURN
      KF=1
      IF (I.GT.1) KF=MB(I-1)+1
      KL=MB(I)-MAX0(1,II-LEQ)
      IF (KF.GT.KL) GOTO 560
      KHI=MB(I)-KF+1
      KJ=0
      DO 550 J=1,NTA
      IC=KJ+(II-KHI)-KF+1
      AIJ=A(KJ+II)
      DO 540 K=KF,KL
  540 A(K+IC)=A(K+IC)-B(K)*AIJ
  550 KJ=J*NEQ
  560 II=II-1
      GOTO 520
C
      END
