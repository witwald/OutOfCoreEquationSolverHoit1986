C=======================================================================
C
C ADDDRV - STAND-IN FOR SIMPAL PROGRAM "ADD" FOLLOWED BY THE SOLVE.
C
C REPRODUCES THE SEQUENCE AND MEMORY-SIZING LOGIC OF PROGRAM ADD AS
C PRINTED IN HOIT (1986), PP. 250-251: PROFIL -> CHOOSE IN-CORE OR
C OUT-OF-CORE BLOCK SIZE FROM KMEM AND MAXREC -> BLKSET -> BLKPNT ->
C RESET KSIZ -> OPEN THE DIRECT ACCESS FILE -> ASEMBL -> ASEMLD ->
C MLOAD. SIMPAL'S DYNAMIC MEMORY MANAGER (DEFINE/DEFINI/DELETE ON
C COMMON A) AND ITS DATA-BASE FILE CALLS (FILEI, FILER, DATOUT) ARE
C REPLACED BY FIXED-SIZE LOCAL ARRAYS.
C
C THE SOLVE STEP (NOT PART OF THE PUBLISHED LISTING) CALLS SORED.
C
C INPUT : KMEMIN  AVAILABLE MEMORY (REAL WORDS), AS KMEM IN ADD
C         MAXREC  MAXIMUM DIRECT ACCESS RECORD (REAL WORDS)
C         ID      NODAL EQUATION NUMBERS ID(NUMNP,6) (FOR MLOAD)
C         NODLD   1 = READ NODAL LOAD LINES FROM UNIT NIN (MLOAD)
C         ISOLV   1 = SORED KKK=1;  2 = KKK=3, THEN 4, THEN 5
C         /CLT/, /PARC/, /IOLIST/ SET BY THE CALLER; ELEMENT FILES
C         ALREADY WRITTEN
C
C OUTPUT: X(NEQ,LOAD) DISPLACEMENTS, TMAS(NEQ) ASSEMBLED MASS,
C         IST(1..12) STATISTICS (SEE BELOW)
C
C=======================================================================
C
      SUBROUTINE ADDDRV(KMEMIN,MAXREC,ID,NODLD,ISOLV,X,TMAS,IST)
      IMPLICIT REAL*8 (A-H,O-Z)
      PARAMETER (MXEQ=1000,MXS=300000,MXEL=3000,MXD=12,MXL=12,
     *           MXB=1000,MXNB=30000)
      CHARACTER*1 NAM,ELNAM
      COMMON /CLT/ ISTAG,NUMNP,NEQ,NEQS,LOAD,MAXD,MAXNA,
     * NUMEL,NEL(20),LENEL(20),NKBLK,NLBLK,KSIZ,KMEM,
     * KYDYN,KYSUB,KYLIN
      COMMON /PARC/ NAM(12),ELNAM(4,20)
      COMMON /IOLIST/ NTM,NTR,NIN,NOT,NT1,NFL,NT2,NT3
      COMMON /DAPAR/ MAXCDA
      COMMON /DASTAT/ NDAR,NDAW,NCRLD
      COMMON /ADDWRK/ STIF(MXS),B(MXS)
      DIMENSION ID(NUMNP,6),X(NEQ,*),TMAS(NEQ),IST(12)
      DIMENSION NA(MXEQ),LM(MXD),ESTF(MXD*(MXD+1)/2),R(MXD*MXL),
     *  EMAS(MXD),KA(4,MXB),KSIZB(MXB),NELP(MXEL),NBKP(MXNB),
     *  MA(MXEQ),MB(MXEQ),D(MXEQ),NN(3),RT(6),KAX(4)
C
      IF(NEQ.GT.MXEQ.OR.MAXD.GT.MXD.OR.LOAD.GT.MXL) STOP 'ADDDRV DIM'
      KMEM=KMEMIN
C-----FIND TOTAL NUMBER OF ELEMENTS -----
      NTNE=0
      DO 10 I=1,NUMEL
   10 NTNE=NTNE+NEL(I)
      IF(NTNE.GT.MXEL) STOP 'ADDDRV MXEL'
C-----FORM PROFILE (KSIZ = TOTAL PROFILE SIZE) -----
      CALL PROFIL(NA,LM,MAXD,NEQ)
C-----SET SIZE OF STIFFNESS BLOCKS (AS IN ADD) -----
      MEMAX=KSIZ+NEQ
      KBP=0
      IF(KMEM.GE.MEMAX.AND.KSIZ.LE.MAXREC) THEN
C-----SET TO SIZE OF TOTAL STIFFNESS - IN-CORE -----
        KLSIZ=(KMEM-KSIZ)/NEQ
        IF(KLSIZ.GT.LOAD) KLSIZ=LOAD
        KLSIZ=KLSIZ*NEQ
        KBP=1
      ELSE
C-----SET TO HALF AVAILABLE MEMORY (OR MAXREC) -----
        KSIZ=KMEM/2
        IF(KSIZ.GT.MAXREC) KSIZ=MAXREC
        KLSIZ=KSIZ/NEQ
        IF(KLSIZ.GT.LOAD) KLSIZ=LOAD
        KLSIZ=KLSIZ*NEQ
      ENDIF
C
      CALL BLKSET(KA,KSIZB,NA,KSZKM,KSIZ,NKBLK,NEQ,MAXNA)
      IF(NKBLK.GT.MXB) STOP 'ADDDRV MXB'
C-----SET BLOCK POINTER -----
      CALL BLKPNT(LM,KA,NELP,NBKP,NALAP,KBP,NTNE)
      IF(NALAP.GT.MXNB) STOP 'ADDDRV MXNB'
C-----KSIZ = LARGER OF MAXIMUM STIFFNESS BLOCK AND LOAD SPACE -----
      IF(KSZKM.GE.KLSIZ) THEN
        KSIZ=KSZKM
      ELSE
        KSIZ=KLSIZ
      ENDIF
      IF(KSIZ.LT.NEQ) THEN
        WRITE(*,3100) NEQ
        STOP 1
      ENDIF
      IF(KSIZ.GT.MXS) STOP 'ADDDRV MXS'
C-----OPEN STIFFNESS FILE -----
C     ADD USES LENK=KSIZ*IP(2)+(MAXNA+6)*IP(1). THE SOLVER ALSO KEEPS
C     A DIAGONAL-POINTER ENTRY PER LOAD VECTOR OF A LOAD BLOCK, SO THE
C     INTEGER PART HOLDS MAX(MAXNA,KSIZ/NEQ) POINTERS PLUS KA(4) AND
C     THE WORD COUNT.
      MAXCDA=MAX(MAXNA,KSIZ/NEQ)
      IF(MAXCDA.GT.MXEQ) STOP 'ADDDRV MAXC'
      LENK=KSIZ*8+(MAXCDA+5)*4
      CALL SOPEN(NT3,'K   ',-LENK)
C-----ASSEMBLE TOTAL STIFFNESS -----
      CALL ASEMBL(STIF,NA,ESTF,R,EMAS,KSIZB,LM,KA,NELP,NBKP,MA,
     *            MAXD,NEQ,ND,LOAD,KSIZ)
C-----ASSEMBLE TOTAL LOAD AND MASS -----
      DO 20 I=1,NEQ
   20 TMAS(I)=0.0D0
      CALL ASEMLD(STIF,ESTF,KA,EMAS,TMAS,LM,R,ND,MAXD,KSIZ)
C-----ASSEMBLE GLOBAL (NODAL) LOADS -----
      IF(NODLD.EQ.1) CALL MLOAD(STIF,RT,ID,NN,KA,NA,NEQ,LOAD,
     *     NUMNP,NKBLK,NLBLK,KSIZ)
C-----RESET KSIZ = MAXIMUM SIZE OF STIFFNESS - IF SINGLE BLOCK -----
      IF(KBP.EQ.1) KSIZ=KSZKM
C
C=====SOLUTION (SORED) =================================================
C     A HOLDS ONE COEFFICIENT BLOCK, B ONE LOAD BLOCK (AND, IF THERE IS
C     MORE THAN ONE COEFFICIENT BLOCK, THE PREVIOUS COEFFICIENT BLOCK)
      MAXA=KSZKM
      MAXB=0
      DO 30 IH=NKBLK+1,NKBLK+NLBLK
   30 MAXB=MAX(MAXB,(KA(4,IH)-KA(3,IH)+1)*NEQ)
      IF(NKBLK.GT.1) MAXB=MAX(MAXB,MAXA)
      NDAR=0
      NDAW=0
      NCRLD=0
      IF(ISOLV.EQ.1) THEN
        CALL SORED(STIF,B,D,MA,MB,NEQ,NEQ,NKBLK,NLBLK,MAXA,MAXB,
     *             MAXCDA,NT3,1)
      ELSE
        CALL SORED(STIF,B,D,MA,MB,NEQ,NEQ,NKBLK,NLBLK,MAXA,MAXB,
     *             MAXCDA,NT3,3)
        CALL SORED(STIF,B,D,MA,MB,NEQ,NEQ,NKBLK,NLBLK,MAXA,MAXB,
     *             MAXCDA,NT3,4)
        CALL SORED(STIF,B,D,MA,MB,NEQ,NEQ,NKBLK,NLBLK,MAXA,MAXB,
     *             MAXCDA,NT3,5)
      ENDIF
C-----RECOVER DISPLACEMENTS FROM THE LOAD RECORDS -----
      DO 60 IH=NKBLK+1,NKBLK+NLBLK
        CALL DABLK(NT3,IH,B,NW,MAXB,MB,MAXCDA,KAX,1)
        DO 50 J=KAX(3),KAX(4)
          K0=(J-KAX(3))*NEQ
          DO 40 I=1,NEQ
   40     X(I,J)=B(K0+I)
   50   CONTINUE
   60 CONTINUE
      CALL FCLOSE(NT3)
C
      IST(1)=NKBLK
      IST(2)=NLBLK
      IST(3)=KBP
      IST(4)=KSZKM
      IST(5)=MAXNA
      IST(6)=NCRLD
      IST(7)=NDAR
      IST(8)=NDAW
      IST(9)=MAXA
      IST(10)=MAXB
      IST(11)=LENK
      IST(12)=NALAP
      RETURN
 3100 FORMAT(//' *** THERE IS NOT ENOUGH MEMORY FOR EVEN 1',
     * ' LOAD VECTOR'/1X,I8,' EQUATIONS ARE TOO MANY ***')
      END
